test('admin request decisions, slot settings and share offer CRUD survive reload without server calls',async()=>{
 const storage=guestStorage()
 storage.set('chagok.guest.role.v1','ADMIN')
 let calls=0
 const fetch=()=>{calls++;throw new Error('Unexpected server call')}
 const rt=runtime(false,fetch,storage),api=rt.load('src/api/admin.ts')
 const original=(await api.listAdminShareOffers(3)).items.length
 await api.decideShareRequest(303,{status:'APPROVED'})
 await api.decideShareRequest(301,{status:'REJECTED',reject_reason:'예시 시간 조정 필요'})
 await api.updateAdminSlot(1008,{is_active:true})
 const created=(await api.createAdminShareOffer(3,{slot_ids:[1005],weekdays:['MON','WED'],start_hour:9,end_hour:18,hourly_price:3,max_hours:2,memo:'체험용 조건'})).items[0]
 await api.updateAdminShareOffer(created.id,{hourly_price:7,is_public:false})
 await api.deleteAdminShareOffer(401)
 const second=runtime(false,fetch,storage),api2=second.load('src/api/admin.ts')
 const requests=await api2.listAdminShareRequests(3)
 assert.equal(requests.items.find(item=>item.id===303).status,'APPROVED')
 assert.equal(requests.items.find(item=>item.id===301).status,'REJECTED')
 assert.equal(second.load('src/mocks/admin.ts').shareRequests.find(item=>item.id===301).reject_reason,'예시 시간 조정 필요')
 assert.equal(requests.items.some(item=>item.id===302 || item.id===304),false)
 assert.equal((await api2.listAdminSlots(3)).items.find(slot=>slot.slot_id===1008).is_active,true)
 const layout=await second.load('src/api/parking.ts').getBuildingLayout(3)
 assert.equal(layout.zones.flatMap(zone=>zone.slots).find(slot=>slot.id===1008).is_active,true)
 const offers=(await api2.listAdminShareOffers(3)).items
 assert.equal(offers.length,original)
 assert.equal(offers.some(offer=>offer.id===401),false)
 assert.equal(offers.find(offer=>offer.id===created.id).hourly_price,7)
 assert.equal(offers.find(offer=>offer.id===created.id).is_public,false)
 assert.equal(offers.find(offer=>offer.id===created.id).memo,'체험용 조건')
 await assert.rejects(api2.decideShareRequest(303,{status:'APPROVED'}),e=>e.status===409)
 const next=(await api2.createAdminShareOffer(3,{slot_ids:[1008],start_hour:9,end_hour:18})).items[0]
 assert.equal(next.id>created.id,true)
 await assert.rejects(api2.getAdminDashboard(999),e=>e.status===403)
 assert.equal(storage.get('chagok.auth'),'real-session-sentinel')
 assert.equal(calls,0)
})

test('resident and administrator state remains independent across role changes and re-entry',async()=>{
 const storage=guestStorage()
 const window={location:{hash:'',reload:()=>{}}}
 const resident=runtime(false,forbiddenFetch,storage,window)
 await resident.load('src/api/auth.ts').updateMe({name:'입주민 진행 상태'})
 await resident.load('src/api/sharedParking.ts').previewGuestShareResult(701,'REJECTED')
 const residentState=storage.get('chagok.guest.state.v1')
 const residentSession=storage.get('chagok.guest.session.v1')
 resident.load('src/api/guestMode.ts').exitGuestDemo()
 resident.load('src/api/guestMode.ts').startGuestDemo('ADMIN')
 const admin=runtime(false,forbiddenFetch,storage,window)
 await admin.load('src/api/auth.ts').updateMe({name:'관리자 진행 상태'})
 await admin.load('src/api/admin.ts').updateAdminSlot(1008,{is_active:true})
 await admin.load('src/api/admin.ts').decideShareRequest(303,{status:'REJECTED',reject_reason:'관리자 체험'})
 assert.equal(storage.get('chagok.guest.state.v1'),residentState)
 assert.equal(storage.get('chagok.guest.session.v1'),residentSession)
 admin.load('src/api/guestMode.ts').exitGuestDemo()
 admin.load('src/api/guestMode.ts').startGuestDemo('RESIDENT')
 const residentAgain=runtime(false,forbiddenFetch,storage,window)
 assert.equal((await residentAgain.load('src/api/auth.ts').getMe()).name,'입주민 진행 상태')
 assert.equal((await residentAgain.load('src/api/sharedParking.ts').getShareRequest(701)).status,'REJECTED')
 const layout=await residentAgain.load('src/api/parking.ts').getBuildingLayout(3)
 assert.equal(layout.zones.flatMap(zone=>zone.slots).find(slot=>slot.id===1008).is_active,false)
 assert.equal(residentAgain.load('src/mocks/admin.ts').shareRequests.find(item=>item.id===303).status,'PENDING')
 await assert.rejects(residentAgain.load('src/api/admin.ts').updateAdminSlot(1008,{is_active:true}),e=>e.status===403)
 residentAgain.load('src/api/guestMode.ts').startGuestDemo('ADMIN')
 const adminAgain=runtime(false,forbiddenFetch,storage)
 assert.equal((await adminAgain.load('src/api/auth.ts').getMe()).name,'관리자 진행 상태')
 assert.equal((await adminAgain.load('src/api/admin.ts').listAdminShareRequests(3)).items.find(item=>item.id===303).status,'REJECTED')
 assert.equal((await adminAgain.load('src/api/admin.ts').listAdminSlots(3)).items.find(item=>item.slot_id===1008).is_active,true)
 assert.equal(storage.get('chagok.auth'),'real-session-sentinel')
})

