test('a newly submitted request and acceptance survive reload with a single token deduction',async()=>{
 const storage=guestStorage(),rt=runtime(false,forbiddenFetch,storage)
 const api=rt.load('src/api/sharedParking.ts'),auth=rt.load('src/api/auth.ts')
 const date=rt.load('src/mocks/sharedParking.ts').SHARED_MOCK_DATE
 const balance=(await auth.getMe()).token_balance
 const created=await api.createShareRequest({offer_id:501,vehicle_id:7,request_date:date,start_hour:7,end_hour:8})
 assert.equal(created.status,'PENDING')
 const reloaded=runtime(false,forbiddenFetch,storage),api2=reloaded.load('src/api/sharedParking.ts')
 assert.equal((await api2.getShareRequest(created.id)).status,'PENDING')
 await api2.previewGuestShareResult(created.id,'APPROVED')
 await assert.rejects(api2.previewGuestShareResult(created.id,'APPROVED'),e=>e.status===409)
 const again=runtime(false,forbiddenFetch,storage)
 assert.equal((await again.load('src/api/sharedParking.ts').getShareRequest(created.id)).status,'APPROVED')
 assert.equal((await again.load('src/api/auth.ts').getMe()).token_balance,balance-created.total_price)
})
