const {test} = require('node:test')
const assert = require('node:assert/strict')
const {runtime} = require('./helpers/runtime.cjs')
const guestStorage = () => new Map([['chagok.guest.v1','true'],['chagok.auth','real-session-sentinel']])
const forbiddenFetch = () => { throw new Error('Guest contacted backend') }
test('guest starts as a ready resident without login and never reaches backend',async()=>{
 const rt=runtime(false,forbiddenFetch,guestStorage()),auth=rt.load('src/api/auth.ts')
 const me=await auth.getMe()
 assert.equal(me.building.role,'RESIDENT');assert.equal(me.onboarding_step,'DONE')
 assert.equal((await rt.load('src/api/parking.ts').getHome()).building.role,'RESIDENT')
 assert.equal((await rt.load('src/api/sharedParking.ts').listGarages()).items.length>0,true)
 await assert.rejects(rt.load('src/api/admin.ts').getAdminDashboard(3),e=>e.status===403)
 await assert.rejects(auth.login({email:'admin@kw.ac.kr',password:'chagok1234'}),e=>e.status===403)
 await assert.rejects(rt.load('src/api/client.ts').request('POST','/anything'),e=>e.status===403)
 assert.equal(rt.storage.get('chagok.auth'),'real-session-sentinel')
})
